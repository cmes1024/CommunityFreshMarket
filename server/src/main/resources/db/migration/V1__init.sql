CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Wave-1 schema. Amounts in fen (integer). Business rows carry store_id (except user).

CREATE TABLE store (

  id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  name          VARCHAR(64)  NOT NULL,
  contact_phone VARCHAR(32)  NULL,
  contact_note  VARCHAR(255) NULL,
  status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
  created_at    TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE TRIGGER trg_store_updated_at
BEFORE UPDATE ON store
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE "user" (

  id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  openid     VARCHAR(64)  NOT NULL,
  nickname   VARCHAR(64)  NULL,
  avatar_url VARCHAR(512) NULL,
  created_at TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_user_openid UNIQUE (openid)
);
CREATE TRIGGER trg_user_updated_at
BEFORE UPDATE ON "user"
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE store_member (

  id         BIGINT      GENERATED BY DEFAULT AS IDENTITY,
  store_id   BIGINT      NOT NULL,
  user_id    BIGINT      NOT NULL,
  role       VARCHAR(16) NOT NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_store_member UNIQUE (store_id, user_id)
);
CREATE INDEX idx_store_member_user ON store_member (user_id);
CREATE TRIGGER trg_store_member_updated_at
BEFORE UPDATE ON store_member
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE category (

  id         BIGINT      GENERATED BY DEFAULT AS IDENTITY,
  store_id   BIGINT      NOT NULL,
  name       VARCHAR(64) NOT NULL,
  sort_order INT         NOT NULL DEFAULT 0,
  enabled    BOOLEAN  NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_category_store ON category (store_id, enabled, sort_order);
CREATE TRIGGER trg_category_updated_at
BEFORE UPDATE ON category
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE product (

  id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  store_id    BIGINT       NOT NULL,
  category_id BIGINT       NOT NULL,
  name        VARCHAR(128) NOT NULL,
  image_url   VARCHAR(512) NULL,
  unit        VARCHAR(16)  NOT NULL,
  price_fen   INT          NOT NULL,
  in_stock    BOOLEAN   NOT NULL DEFAULT TRUE,
  on_shelf    BOOLEAN   NOT NULL DEFAULT TRUE,
  stock_qty   INT          NULL,
  created_at  TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_product_store_cat ON product (store_id, category_id, on_shelf);
CREATE INDEX idx_product_store_shelf ON product (store_id, on_shelf, in_stock);
CREATE TRIGGER trg_product_updated_at
BEFORE UPDATE ON product
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE user_address (

  id         BIGINT      GENERATED BY DEFAULT AS IDENTITY,
  user_id    BIGINT      NOT NULL,
  store_id   BIGINT      NOT NULL,
  phone      VARCHAR(32) NOT NULL,
  community  VARCHAR(64) NOT NULL,
  building   VARCHAR(64) NULL,
  room       VARCHAR(64) NULL,
  is_default BOOLEAN  NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_address_user_store ON user_address (user_id, store_id);
CREATE TRIGGER trg_user_address_updated_at
BEFORE UPDATE ON user_address
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE pickup_slot (

  id         BIGINT      GENERATED BY DEFAULT AS IDENTITY,
  store_id   BIGINT      NOT NULL,
  label      VARCHAR(64) NOT NULL,
  sort_order INT         NOT NULL DEFAULT 0,
  enabled    BOOLEAN  NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_pickup_slot_store ON pickup_slot (store_id, enabled, sort_order);
CREATE TRIGGER trg_pickup_slot_updated_at
BEFORE UPDATE ON pickup_slot
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE cart_item (

  id         BIGINT      GENERATED BY DEFAULT AS IDENTITY,
  user_id    BIGINT      NOT NULL,
  store_id   BIGINT      NOT NULL,
  product_id BIGINT      NOT NULL,
  qty        DECIMAL(10, 2) NOT NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_cart_item UNIQUE (user_id, store_id, product_id)
);
CREATE INDEX idx_cart_user_store ON cart_item (user_id, store_id);
CREATE TRIGGER trg_cart_item_updated_at
BEFORE UPDATE ON cart_item
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE "order" (

  id                   BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  store_id             BIGINT       NOT NULL,
  user_id              BIGINT       NOT NULL,
  fulfillment          VARCHAR(16)  NOT NULL,
  status               VARCHAR(32)  NOT NULL,
  asap                 BOOLEAN   NOT NULL DEFAULT TRUE,
  remark               VARCHAR(512) NULL,
  address_snapshot     TEXT         NULL,
  pickup_slot_id       BIGINT       NULL,
  pickup_slot_label    VARCHAR(64)  NULL,
  total_amount_fen     INT          NOT NULL DEFAULT 0,
  merchant_unread      BOOLEAN   NOT NULL DEFAULT TRUE,
  customer_arrived_at  TIMESTAMP(3)  NULL,
  cancel_by            VARCHAR(16)  NULL,
  cancel_reason        VARCHAR(255) NULL,
  cancelled_at         TIMESTAMP(3)  NULL,
  created_at           TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at           TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_order_store_status ON "order" (store_id, status, created_at);
CREATE INDEX idx_order_user ON "order" (user_id, created_at);
CREATE INDEX idx_order_merchant_unread ON "order" (store_id, merchant_unread, status);
CREATE TRIGGER trg_order_updated_at
BEFORE UPDATE ON "order"
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE order_item (

  id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  order_id        BIGINT       NOT NULL,
  store_id        BIGINT       NOT NULL,
  product_id      BIGINT       NULL,
  product_name    VARCHAR(128) NOT NULL,
  unit            VARCHAR(16)  NOT NULL,
  unit_price_fen  INT          NOT NULL,
  qty             DECIMAL(10, 2) NOT NULL,
  amount_fen      INT          NOT NULL,
  created_at      TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_order_item_order ON order_item (order_id);

CREATE TABLE restock_watch (

  id           BIGINT      GENERATED BY DEFAULT AS IDENTITY,
  user_id      BIGINT      NOT NULL,
  store_id     BIGINT      NOT NULL,
  product_id   BIGINT      NOT NULL,
  status       VARCHAR(16) NOT NULL DEFAULT 'WATCHING',
  created_at   TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  notified_at  TIMESTAMP(3) NULL,
  PRIMARY KEY (id),
  CONSTRAINT uk_restock_user_product UNIQUE (user_id, store_id, product_id)
);
CREATE INDEX idx_restock_product ON restock_watch (store_id, product_id, status);

