CREATE TABLE balance_account (

  user_id     BIGINT       NOT NULL,
  store_id    BIGINT       NOT NULL,
  balance_fen INT          NOT NULL DEFAULT 0,
  updated_at  TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, store_id)
);
CREATE INDEX idx_balance_account_store ON balance_account (store_id);
CREATE TRIGGER trg_balance_account_updated_at
BEFORE UPDATE ON balance_account
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE balance_ledger (

  id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  store_id           BIGINT       NOT NULL,
  user_id            BIGINT       NOT NULL,
  delta_fen          INT          NOT NULL,
  balance_after_fen  INT          NOT NULL,
  reason             VARCHAR(16)  NOT NULL,
  ref_type           VARCHAR(16)  NULL,
  ref_id             BIGINT       NULL,
  operator_user_id   BIGINT       NULL,
  remark             VARCHAR(128) NULL,
  created_at         TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_balance_ledger_user ON balance_ledger (store_id, user_id, id);
CREATE INDEX idx_balance_ledger_ref ON balance_ledger (store_id, ref_type, ref_id, reason);

ALTER TABLE "order"
  ADD COLUMN balance_fen INT NOT NULL DEFAULT 0;
