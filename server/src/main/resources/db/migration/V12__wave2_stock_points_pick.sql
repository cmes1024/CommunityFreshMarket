-- Wave 2: stock / min-max qty / points / pick session
-- Wave 3 skeleton: coupon / cashier / checkin

ALTER TABLE product
  ALTER COLUMN stock_qty TYPE DECIMAL(10, 2),
  ADD COLUMN min_qty DECIMAL(10, 2) NULL,
  ADD COLUMN max_qty DECIMAL(10, 2) NULL;

ALTER TABLE store
  ADD COLUMN points_per_yuan INT NOT NULL DEFAULT 1,
  ADD COLUMN pick_image_ttl_minutes INT NOT NULL DEFAULT 15;

CREATE TABLE point_account (

  user_id    BIGINT       NOT NULL,
  store_id   BIGINT       NOT NULL,
  balance    INT          NOT NULL DEFAULT 0,
  updated_at TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, store_id)
);
CREATE INDEX idx_point_account_store ON point_account (store_id);
CREATE TRIGGER trg_point_account_updated_at
BEFORE UPDATE ON point_account
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE point_ledger (

  id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  store_id      BIGINT       NOT NULL,
  user_id       BIGINT       NOT NULL,
  delta         INT          NOT NULL,
  balance_after INT          NOT NULL,
  reason        VARCHAR(32)  NOT NULL,
  ref_type      VARCHAR(32)  NULL,
  ref_id        BIGINT       NULL,
  remark        VARCHAR(256) NULL,
  created_at    TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_point_ledger_user ON point_ledger (store_id, user_id, id);
CREATE INDEX idx_point_ledger_ref ON point_ledger (store_id, ref_type, ref_id);

CREATE TABLE point_redeem (

  id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  store_id    BIGINT       NOT NULL,
  user_id     BIGINT       NOT NULL,
  cost_points INT          NOT NULL,
  title       VARCHAR(128) NOT NULL,
  status      VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
  created_at  TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_point_redeem_store_status ON point_redeem (store_id, status, id);
CREATE INDEX idx_point_redeem_user ON point_redeem (store_id, user_id, id);
CREATE TRIGGER trg_point_redeem_updated_at
BEFORE UPDATE ON point_redeem
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE pick_session (

  id                  BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  store_id            BIGINT        NOT NULL,
  product_id          BIGINT        NOT NULL,
  customer_user_id    BIGINT        NOT NULL,
  status              VARCHAR(24)   NOT NULL,
  image_url           VARCHAR(512)  NULL,
  expires_at          TIMESTAMP(3)   NULL,
  lock_holder_user_id BIGINT        NULL,
  marks_json          TEXT          NULL,
  confirmed_qty       DECIMAL(10,2) NULL,
  order_id            BIGINT        NULL,
  created_at          TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at          TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_pick_product_active ON pick_session (store_id, product_id, status);
CREATE INDEX idx_pick_customer ON pick_session (store_id, customer_user_id, id);
CREATE TRIGGER trg_pick_session_updated_at
BEFORE UPDATE ON pick_session
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE coupon (

  id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  store_id        BIGINT       NOT NULL,
  title           VARCHAR(64)  NOT NULL,
  type            VARCHAR(16)  NOT NULL,
  face_fen        INT          NOT NULL,
  min_spend_fen   INT          NOT NULL DEFAULT 0,
  total_limit     INT          NULL,
  per_user_limit  INT          NOT NULL DEFAULT 1,
  claimed_count   INT          NOT NULL DEFAULT 0,
  starts_at       TIMESTAMP(3)  NULL,
  ends_at         TIMESTAMP(3)  NULL,
  enabled         BOOLEAN   NOT NULL DEFAULT TRUE,
  created_at      TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_coupon_store ON coupon (store_id, enabled);
CREATE TRIGGER trg_coupon_updated_at
BEFORE UPDATE ON coupon
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE coupon_claim (

  id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  coupon_id  BIGINT       NOT NULL,
  store_id   BIGINT       NOT NULL,
  user_id    BIGINT       NOT NULL,
  status     VARCHAR(16)  NOT NULL DEFAULT 'UNUSED',
  order_id   BIGINT       NULL,
  cashier_id BIGINT       NULL,
  claimed_at TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  used_at    TIMESTAMP(3)  NULL,
  PRIMARY KEY (id)
);
CREATE INDEX idx_claim_user ON coupon_claim (store_id, user_id, status);
CREATE INDEX idx_claim_coupon ON coupon_claim (coupon_id, status);

CREATE TABLE cashier_sale (

  id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  store_id        BIGINT       NOT NULL,
  member_user_id  BIGINT       NULL,
  status          VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
  total_fen       INT          NOT NULL DEFAULT 0,
  discount_fen    INT          NOT NULL DEFAULT 0,
  pay_fen         INT          NOT NULL DEFAULT 0,
  adjust_reason   VARCHAR(128) NULL,
  created_by      BIGINT       NOT NULL,
  completed_at    TIMESTAMP(3)  NULL,
  created_at      TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_cashier_store ON cashier_sale (store_id, status, id);
CREATE TRIGGER trg_cashier_sale_updated_at
BEFORE UPDATE ON cashier_sale
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE cashier_sale_item (

  id              BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  sale_id         BIGINT        NOT NULL,
  store_id        BIGINT        NOT NULL,
  product_id      BIGINT        NULL,
  product_name    VARCHAR(128)  NOT NULL,
  unit            VARCHAR(16)   NOT NULL,
  unit_price_fen  INT           NOT NULL,
  qty             DECIMAL(10,2) NOT NULL,
  amount_fen      INT           NOT NULL,
  adjusted        BOOLEAN    NOT NULL DEFAULT FALSE,
  created_at      TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_cashier_item_sale ON cashier_sale_item (sale_id);

CREATE TABLE member_checkin (

  id          BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  store_id    BIGINT        NOT NULL,
  user_id     BIGINT        NOT NULL,
  expires_at  TIMESTAMP(3)   NOT NULL,
  consumed_at TIMESTAMP(3)   NULL,
  lat         DECIMAL(10,6) NULL,
  lng         DECIMAL(10,6) NULL,
  created_at  TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_checkin_active ON member_checkin (store_id, expires_at, consumed_at);
CREATE INDEX idx_checkin_user ON member_checkin (store_id, user_id, id);
