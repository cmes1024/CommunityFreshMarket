-- 商家配置兑换物；顾客按条目兑换，申请单记下当时的名称和积分

CREATE TABLE point_redeem_item (

  id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  store_id    BIGINT       NOT NULL,
  title       VARCHAR(128) NOT NULL,
  cost_points INT          NOT NULL,
  enabled     BOOLEAN   NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX idx_point_redeem_item_store ON point_redeem_item (store_id, enabled, id);
CREATE TRIGGER trg_point_redeem_item_updated_at
BEFORE UPDATE ON point_redeem_item
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE point_redeem
  ADD COLUMN item_id BIGINT NULL;
