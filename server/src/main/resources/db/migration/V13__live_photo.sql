-- 商品实景图：开关、图、拍摄时间；未处理更新申请（同一商品一条）

ALTER TABLE product
  ADD COLUMN live_photo_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN live_photo_url VARCHAR(512) NULL,
  ADD COLUMN live_photo_taken_at TIMESTAMP(3) NULL;

CREATE TABLE live_photo_request (

  id                 BIGINT      GENERATED BY DEFAULT AS IDENTITY,
  store_id           BIGINT      NOT NULL,
  product_id         BIGINT      NOT NULL,
  applicant_count    INT         NOT NULL DEFAULT 0,
  last_requested_at  TIMESTAMP(3) NOT NULL,
  created_at         TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at         TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_live_photo_request_product UNIQUE (product_id)
);
CREATE INDEX idx_live_photo_request_store ON live_photo_request (store_id, last_requested_at);
CREATE TRIGGER trg_live_photo_request_updated_at
BEFORE UPDATE ON live_photo_request
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE live_photo_request_user (

  id          BIGINT      GENERATED BY DEFAULT AS IDENTITY,
  request_id  BIGINT      NOT NULL,
  user_id     BIGINT      NOT NULL,
  created_at  TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_live_photo_request_user UNIQUE (request_id, user_id)
);
